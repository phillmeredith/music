export const isCarrier = (alg0, n) => CARRIERS[alg0 & 31].includes(n);

// Returns { banks: [4][32] of { vmem, extras } }
export function factoryBanks() {
  const base = BASE.map(([name, alg, fb, ops, x, app]) => ({ vced: makeVoice(name, alg, fb, ops, x || {}), extras: app || X(null) }));
  const suffix = { soft: 'Sf', bright: 'Br', wide: 'Wd' };
  const banks = [base];
  for (const kind of ['soft', 'bright', 'wide']) {
    banks.push(base.map((b) => {
      const v = variant(b.vced, kind);
      const nm = String.fromCharCode(...b.vced.subarray(145, 155)).trim();
      setVoiceName(v, nm.slice(0, 7).trim() + ' ' + suffix[kind]);
      return { vced: v, extras: JSON.parse(JSON.stringify(b.extras)) };
    }));
  }
  return banks.map((bank) => bank.map(({ vced, extras }) => ({ vmem: vcedToVmem(vced), extras })));
}

