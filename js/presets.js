const clamp = (x, lo, hi) => Math.max(lo, Math.min(hi, x));

function variant(v, kind) {
  const out = new Uint8Array(v);
  const alg = out[G.ALG];
  for (let n = 1; n <= 6; n++) {
    const b = opOff(n);
    const ol = out[b + OPF.OL];
    if (!ol) continue;
    // carriers are left alone for level; modulators shape the colour
    const carrier = isCarrier(alg, n);
    if (kind === 'soft') {
      if (!carrier) out[b + OPF.OL] = clamp(ol - 8, 0, 99);
      out[b + OPF.R1] = clamp(out[b + OPF.R1] - 12, 20, 99);
      out[b + OPF.R4] = clamp(out[b + OPF.R4] - 10, 20, 99);
    } else if (kind === 'bright') {
      if (!carrier) out[b + OPF.OL] = clamp(ol + 6, 0, 99);
      out[b + OPF.KVS] = clamp(out[b + OPF.KVS] + 1, 0, 7);
    } else if (kind === 'wide') {
      if (carrier) out[b + OPF.DET] = n % 2 ? 9 : 5;
    }
  }
  if (kind === 'bright') out[G.FB] = clamp(out[G.FB] + 1, 0, 7);
  if (kind === 'wide') { out[G.PMD] = Math.max(out[G.PMD], 5); out[G.LFD] = Math.max(out[G.LFD], 40); out[G.LFS] = 33; out[G.PMS] = Math.max(out[G.PMS], 3); }
  return out;
}

