// Sixop's own factory voices. These are original patches written for this app
// (the stock FM-1 bank is mostly Yamaha/community DX7 data, so it is not shipped).
// Bank A: 32 hand-built voices. Banks B-D: deterministic variations of them
// (softer, brighter, wider), so the layout matches the hardware's 4 x 32.
import { vcedToVmem, setVoiceName, opOff, OPF, G } from './dx7.js';

const OP = (o = {}) => ({
  r: o.r || [99, 99, 99, 99], l: o.l || [99, 99, 99, 0], ol: o.ol ?? 0,
  c: o.c ?? 1, f: o.f ?? 0, det: o.det ?? 7, fixed: o.fixed ? 1 : 0,
  kvs: o.kvs ?? 2, ams: o.ams ?? 0, rs: o.rs ?? 0,
  bp: o.bp ?? 39, ld: o.ld ?? 0, rd: o.rd ?? 0, lc: o.lc ?? 0, rc: o.rc ?? 0,
});

export function makeVoice(name, alg, fb, ops, x = {}) {
  const v = new Uint8Array(156);
  for (let n = 1; n <= 6; n++) {
    const o = OP(ops[n - 1]), b = opOff(n);
    for (let i = 0; i < 4; i++) { v[b + i] = o.r[i]; v[b + 4 + i] = o.l[i]; }
    v[b + OPF.BP] = o.bp; v[b + OPF.LD] = o.ld; v[b + OPF.RD] = o.rd; v[b + OPF.LC] = o.lc; v[b + OPF.RC] = o.rc;
    v[b + OPF.RS] = o.rs; v[b + OPF.AMS] = o.ams; v[b + OPF.KVS] = o.kvs; v[b + OPF.OL] = o.ol;
    v[b + OPF.MODE] = o.fixed; v[b + OPF.COARSE] = o.c; v[b + OPF.FINE] = o.f; v[b + OPF.DET] = o.det;
  }
  const pe = x.pe || { r: [99, 99, 99, 99], l: [50, 50, 50, 50] };
  for (let i = 0; i < 4; i++) { v[G.PR1 + i] = pe.r[i]; v[G.PL1 + i] = pe.l[i]; }
  v[G.ALG] = alg - 1; v[G.FB] = fb; v[G.OKS] = x.oks ?? 1;
  const lfo = Object.assign({ speed: 35, delay: 0, pmd: 0, amd: 0, sync: 0, wave: 4, pms: 3 }, x.lfo || {});
  v[G.LFS] = lfo.speed; v[G.LFD] = lfo.delay; v[G.PMD] = lfo.pmd; v[G.AMD] = lfo.amd;
  v[G.LKS] = lfo.sync; v[G.WAVE] = lfo.wave; v[G.PMS] = lfo.pms;
  v[G.TRNP] = 24 + (x.tr || 0);
  setVoiceName(v, name);
  return v;
}

