// Generates web/js/params.js from engine/src/params.h so IDs never drift.
import { readFileSync, writeFileSync } from 'node:fs';
const src = readFileSync(new URL('../engine/src/params.h', import.meta.url), 'utf8');
const out = ['// Generated by tools/gen-params.mjs from engine/src/params.h. Do not edit.', 'export const P = {'];
for (const m of src.matchAll(/^\s*(P_\w+|PP_\w+)\s*=\s*([^,]+),/gm)) {
  const expr = m[2].replace(/\/\*.*$/, '').trim();
  out.push(`  ${m[1]}: ${expr},`);
}
out.push('};', '');
writeFileSync(new URL('../web/js/params.js', import.meta.url), out.join('\n'));
console.log('wrote web/js/params.js');
